"""
ollama-rag-starter — Web UI (Gradio)

Usage:
    python app.py              # normal mode (needs Ollama running)
    python app.py --demo       # demo mode with mock answers (no Ollama needed)
"""

import os
import sys
import glob
import numpy as np

# ---- Demo mode: skip real Ollama imports ----
DEMO_MODE = "--demo" in sys.argv

if not DEMO_MODE:
    import ollama

EMBED_MODEL = "nomic-embed-text"
CHAT_MODEL = "qwen2.5:7b"
CHUNK_SIZE = 500
CHUNK_OVERLAP = 80
TOP_K = 3
DOCS_DIR = "docs"


# ---------- Document loading ----------
def load_documents(docs_dir=DOCS_DIR):
    texts = []
    for path in glob.glob(os.path.join(docs_dir, "**/*"), recursive=True):
        if path.endswith((".txt", ".md")):
            with open(path, "r", encoding="utf-8") as f:
                texts.append((os.path.basename(path), f.read()))
    return texts


def chunk_text(text, size=CHUNK_SIZE, overlap=CHUNK_OVERLAP):
    chunks, start = [], 0
    while start < len(text):
        chunks.append(text[start:start + size])
        start = start + size - overlap
    return [c.strip() for c in chunks if c.strip()]


# ---------- Demo mode: fake retrieval ----------
DEMO_ANSWERS = {
    "ollama": "Ollama is a free, open-source tool that lets you run large language models locally on your own computer. Install it from ollama.com, then run `ollama pull qwen2.5:7b` to download a model.",
    "rag": "RAG (Retrieval-Augmented Generation) works by: splitting your docs into chunks, embedding them, finding the chunks closest to your question via cosine similarity, then feeding those chunks into the LLM as context.",
    "local": "Running RAG locally means your documents never leave your machine. No API bills, no privacy concerns, works offline — as long as you have Ollama and enough RAM/VRAM.",
    "install": "1) Install Ollama from ollama.com/download  2) Run `ollama pull nomic-embed-text`  3) Run `ollama pull qwen2.5:7b`  4) `pip install -r requirements.txt`  5) `python rag.py`",
}


def demo_answer(question):
    q = question.lower()
    for key, ans in DEMO_ANSWERS.items():
        if key in q:
            return ans, ["sample.txt"], [0.721, 0.615, 0.588]
    return ("This is a demo answer. In real mode, this would be generated by your local "
            "Ollama model based on the retrieved document chunks. Try asking about "
            "Ollama, RAG, or local LLM setup."), ["sample.txt"], [0.654, 0.523, 0.498]


# ---------- Real mode ----------
def embed(texts):
    resp = ollama.embed(model=EMBED_MODEL, input=texts)
    return np.array(resp["embeddings"], dtype=np.float32)


def retrieve(query_emb, corpus_emb, top_k=TOP_K):
    q = query_emb / np.linalg.norm(query_emb, axis=1, keepdims=True)
    c = corpus_emb / np.linalg.norm(corpus_emb, axis=1, keepdims=True)
    scores = (c @ q.T).flatten()
    idxs = np.argsort(scores)[::-1][:top_k]
    return idxs, scores[idxs]


def build_index(docs_dir=DOCS_DIR):
    all_chunks = []
    for fname, content in load_documents(docs_dir):
        for chunk in chunk_text(content):
            all_chunks.append((fname, chunk))
    if not all_chunks:
        return [], np.array([])
    corpus_emb = embed([c[1] for c in all_chunks])
    return all_chunks, corpus_emb


def real_answer(question, all_chunks, corpus_emb):
    q_emb = embed([question])
    idxs, scores = retrieve(q_emb, corpus_emb)
    context = "\n\n".join([f"[{all_chunks[i][0]}]\n{all_chunks[i][1]}" for i in idxs])
    prompt = f"Answer based ONLY on the context. If unknown, say so.\n\nContext:\n{context}\n\nQuestion: {question}\nAnswer:"
    resp = ollama.chat(model=CHAT_MODEL, messages=[{"role": "user", "content": prompt}])
    return resp["message"]["content"], [all_chunks[i][0] for i in idxs], [round(float(s), 3) for s in scores]


# ---------- Gradio UI ----------
import gradio as gr

state = {"chunks": [], "emb": None}


def init_index():
    if DEMO_MODE:
        return "✅ Demo mode loaded (no Ollama needed). Ask a question!"
    try:
        chunks, emb = build_index()
        if not chunks:
            state["chunks"], state["emb"] = [], None
            return "⚠️ No .txt/.md files found in ./docs/ — add documents first."
        state["chunks"], state["emb"] = chunks, emb
        return f"✅ Indexed {len(chunks)} chunks from {len(set(c[0] for c in chunks))} file(s)."
    except Exception as e:
        return f"⚠️ Index failed: {e}. Is Ollama running?"


def ask(question, history):
    if DEMO_MODE:
        ans, sources, scores = demo_answer(question)
    else:
        if not state["chunks"]:
            status = init_index()
            if not state["chunks"]:
                return status
        ans, sources, scores = real_answer(question, state["chunks"], state["emb"])
    sources_md = " | ".join(f"`{s}` ({sc})" for s, sc in zip(sources, scores))
    return f"{ans}\n\n---\n*Sources: {sources_md}*"


def build_ui():
    with gr.Blocks(title="Ollama RAG Starter") as demo:
        gr.Markdown("# 🦙 Ollama RAG Starter\nAsk questions over your local documents — fully offline.")

        status = gr.Textbox(label="Status", value=init_index(), interactive=False)

        with gr.Row():
            with gr.Column(scale=2):
                gr.ChatInterface(
                    fn=ask,
                    chatbot=gr.Chatbot(height=420, placeholder="Ask a question about your documents..."),
                    textbox=gr.Textbox(placeholder="e.g. What is Ollama?", scale=7),
                    examples=["What is Ollama?", "How do I install it?", "Why run RAG locally?"],
                )
            with gr.Column(scale=1):
                gr.Markdown("### 📁 Documents")
                files = glob.glob(os.path.join(DOCS_DIR, "*.txt")) + glob.glob(os.path.join(DOCS_DIR, "*.md"))
                if files:
                    for f in files:
                        gr.Markdown(f"- `{os.path.basename(f)}`")
                else:
                    gr.Markdown("_No documents yet. Drop .txt/.md files in `docs/`_")

                gr.Markdown("### ⚙️ Config")
                gr.Markdown(f"- Chat model: `{CHAT_MODEL}`\n- Embedding: `{EMBED_MODEL}`\n- Top-K: `{TOP_K}`\n- Chunk size: `{CHUNK_SIZE}`")

    return demo


if __name__ == "__main__":
    demo = build_ui()
    demo.launch(server_name="127.0.0.1", server_port=7860, share=False)
